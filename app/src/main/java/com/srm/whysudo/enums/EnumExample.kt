import com.srm.whysudo.utils.Utils

object EnumExample {
    fun k(): String {
        val a = "githuv"
        return a[5].toString()
    }

    fun jg(): String {
        return "You Can!/:."
    }

    fun d(): String {
        return Char(61).toString()
    }

    fun _1_(): String {
        return Char(49).toString()
    }

    fun ___c(): String {
        return Utils.x(Char(57).toString())
    }

    fun __b(): String {
        return Utils.x(Char(98).toString())
    }
}